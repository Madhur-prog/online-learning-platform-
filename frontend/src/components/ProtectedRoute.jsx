import React from 'react';
import { Navigate, useLocation } from 'react-router-dom';
import { useAuth } from '../hooks/useAuth';
import LoadingSpinner from './LoadingSpinner';

const ProtectedRoute = ({ children, allowedRoles }) => {
  const { user, isAuthenticated, loading } = useAuth();
  const location = useLocation();

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50">
        <LoadingSpinner text="Checking authentication status..." />
      </div>
    );
  }

  if (!isAuthenticated) {
    return <Navigate to="/login" state={{ from: location }} replace />;
  }

  if (allowedRoles && !allowedRoles.includes(user?.role)) {
    // If student tries to visit instructor page, redirect to student dashboard
    if (user?.role === 'student') {
      return <Navigate to="/dashboard" replace />;
    }
    // If instructor tries to visit student dashboard, redirect to instructor dashboard
    return <Navigate to="/instructor" replace />;
  }

  return children;
};

export default ProtectedRoute;
